"""
Example: Loop Practice
Learn different types of loops in Python
"""

# For loop - Loop 1 to 10
print("For loop 1-10:")
for i in range(1, 11):
    print(i, end=" ")
print("\n")

# While loop example
print("While loop example:")
count = 1
while count <= 5:
    print(f"Count: {count}")
    count += 1
